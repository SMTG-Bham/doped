from pathlib import Path

from pymatgen.core.lattice import Lattice
from pymatgen.core.structure import Structure

from doped.generation import DefectsGenerator
from doped.io.gpaw import DefectDictSet, DefectsSet


def write_competing_phase_inputs(gpaw_settings, host_structure):
    """Write GPAW single-point inputs for the host and elemental references."""
    # (Manual for now: this will soon be replaced by automated competing-phase input generation in doped)
    script_dir = Path(__file__).resolve().parent
    competing_phases_dir = script_dir.parent / "MgO" / "CompetingPhases"
    output_dir = Path("CompetingPhases_GPAW")

    # The host phase is the primitive cell of the defect host structure, with the same k-point density as
    # the other phases (the Γ-only bulk supercell is not k-converged, which cancels in defect formation
    # energies but not in the chemical potentials). The other structures were generated by the doped
    # CompetingPhases workflow.
    phase_structures = {"MgO_Fm-3m_EaH_0": host_structure.get_primitive_structure()}
    for phase_name in ("Mg_Fm-3m_EaH_0", "Mg_P6_3mmc_EaH_0.009", "Mg_R-3m_EaH_0.003", "O2_mmm_EaH_0"):
        structure_path = competing_phases_dir / phase_name / "vasp_std" / "POSCAR"
        if not structure_path.exists():
            raise FileNotFoundError(
                f"Missing CompetingPhases structure: {structure_path}. "
                "Run this script from a full doped source checkout."
            )
        # (Niggli-reduced, as GPAW warns that results may be wrong for skewed cells, e.g. Mg_Fm-3m_EaH_0):
        phase_structures[phase_name] = Structure.from_file(structure_path).get_reduced_structure()

    for phase_name, phase_structure in phase_structures.items():
        phase_settings = {
            **gpaw_settings,
            "kpts": {"density": 4.0, "gamma": True},
            "occupations": {"name": "fermi-dirac", "width": 0.1},
        }
        if phase_name.startswith("O2_"):
            # Isolated triplet O2: Gamma-only sampling and one initial moment
            # on each oxygen atom.
            phase_settings.update(
                {
                    "kpts": {"size": (1, 1, 1), "gamma": True},
                    "occupations": {"name": "fermi-dirac", "width": 0.01},
                    "initial_magnetic_moments": [1.0, 1.0],
                }
            )

        print(f"Setting up competing phase {phase_name}...")
        phase_set = DefectDictSet(
            phase_structure,
            charge_state=0,
            gpaw_settings=phase_settings,
            calculation_type="singlepoint",
        )
        phase_set.write_input(output_dir / phase_name)


def main():
    print("Generating MgO bulk structure natively...")
    # Native structure generation
    lattice = Lattice.cubic(4.21)
    bulk_structure = Structure.from_spacegroup(
        "Fm-3m",
        lattice,
        ["Mg", "O"],
        [[0, 0, 0], [0.5, 0.5, 0.5]],
    )

    print("Generating MgO defects (forcing Mg_O antisites)...")
    # Force the generation of the Mg_O antisite using the extrinsic flag
    defect_gen = DefectsGenerator(bulk_structure, extrinsic={"O": "Mg"})

    # GPAW Parameters
    gpaw_settings = {
        "mode": {"name": "pw", "ecut": 400},  # (lower cutoffs give inconsistent bulk/host-phase energies)
        "kpts": {"size": (1, 1, 1), "gamma": True},
        "xc": "PBE",
    }

    print("Writing GPAW input files...")

    # Write a ``<defect name>/relax.py`` relaxation for each defect, and a static reference calculation for
    # the bulk supercell (``MgO_bulk/singlepoint.py``):
    DefectsSet(defect_gen, gpaw_settings=gpaw_settings).write_files()

    for defect_name, defect_entry in defect_gen.defect_entries.items():
        # Create a true static single-point example for the Mg_O +1 state
        if "Mg_O" in defect_name and defect_entry.charge_state == 1:
            unrelaxed_name = defect_name + "_unrelaxed"
            print(f"Setting up {unrelaxed_name}...")

            singlepoint_set = DefectDictSet(
                defect_entry.defect_supercell,
                charge_state=defect_entry.charge_state,
                gpaw_settings=gpaw_settings,
                calculation_type="singlepoint",
            )
            singlepoint_set.write_input(unrelaxed_name)

    print("Writing GPAW inputs for the MgO and Mg/O competing phases...")
    write_competing_phase_inputs(gpaw_settings, bulk_structure)

    print("Workflow setup complete! You can now run the calculations.")


if __name__ == "__main__":
    main()
